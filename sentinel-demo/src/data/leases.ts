// Helper to get lease by filename
export function getLeaseByFilename(filename: string): Lease | undefined {
  // Handle both .pdf and .txt extensions
  const normalizedFilename = filename.replace('.txt', '.pdf');
  return mockLeases.find(lease => lease.filename === normalizedFilename);
}
